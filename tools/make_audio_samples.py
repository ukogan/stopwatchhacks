"""Build the speaker-test clips as a C header for the audio test firmware.

Usage: python3 tools/make_audio_samples.py <speech.wav> <out_header> [song.wav]
  speech.wav: 16 kHz mono 16-bit (e.g. from macOS `say`).
  song.wav:   optional real music clip, 24 kHz mono 16-bit (e.g. via ffmpeg).
              Without it, a short synthesized tune is used instead.
Also synthesizes a frequency sweep.
"""
import math
import struct
import sys
import wave

RATE = 16000


def read_wav(path, rate=RATE):
    with wave.open(path, "rb") as w:
        assert w.getframerate() == rate and w.getnchannels() == 1 and w.getsampwidth() == 2, path
        raw = w.readframes(w.getnframes())
    return list(struct.unpack("<%dh" % (len(raw) // 2), raw))


def note(freq, dur, amp, harmonics=(1.0, 0.5, 0.25), attack=0.01, release=0.25):
    n = int(dur * RATE)
    out = []
    for i in range(n):
        t = i / RATE
        env = min(1.0, t / attack) * (1.0 if t < dur - release else max(0.0, (dur - t) / release))
        v = sum(h * math.sin(2 * math.pi * freq * (k + 1) * t) for k, h in enumerate(harmonics))
        out.append(amp * env * v / sum(harmonics))
    return out


def mix(dst, src, start):
    for i, v in enumerate(src):
        if start + i < len(dst):
            dst[start + i] += v


def music():
    bpm = 100
    beat = 60 / bpm
    total = int(16 * beat * RATE)
    buf = [0.0] * total
    hz = lambda m: 440 * 2 ** ((m - 69) / 12)
    chords = [[57, 60, 64], [53, 57, 60], [48, 52, 55], [55, 59, 62]]  # Am F C G
    for bar, chord in enumerate(chords):
        for m in chord:
            mix(buf, note(hz(m), 4 * beat, 0.12, release=0.6), int(bar * 4 * beat * RATE))
        mix(buf, note(hz(chord[0] - 12), 4 * beat, 0.18, (1.0, 0.3), release=0.6), int(bar * 4 * beat * RATE))
    melody = [76, 74, 72, 74, 76, 76, 76, 0, 74, 74, 74, 0, 76, 79, 79, 0]
    for i, m in enumerate(melody):
        if m:
            mix(buf, note(hz(m), beat * 0.9, 0.22, (1.0, 0.4, 0.2, 0.1), release=0.15), int(i * beat * RATE))
    return buf


def sweep(seconds=4.0, f0=100, f1=8000):
    n = int(seconds * RATE)
    k = math.log(f1 / f0)
    return [0.35 * math.sin(2 * math.pi * f0 * seconds / k * (math.exp(k * i / n) - 1)) for i in range(n)]


def to_int16(samples):
    peak = max(1e-9, max(abs(s) for s in samples))
    scale = 30000 / peak if peak > 1.5 else 32767
    return [max(-32768, min(32767, int(s * scale))) for s in samples]


def emit(name, data, f):
    f.write("const int16_t %s[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 16):
        f.write("  " + ", ".join(str(v) for v in data[i:i + 16]) + ",\n")
    f.write("};\n\n")


def main():
    speech_path, out_path = sys.argv[1], sys.argv[2]
    speech = read_wav(speech_path)
    with open(out_path, "w") as f:
        f.write("// Generated by tools/make_audio_samples.py. 16 kHz mono.\n#pragma once\n#include <stdint.h>\n\n")
        f.write("constexpr uint32_t kSampleRate = %d;\n\n" % RATE)
        emit("kSpeech", speech, f)
        if len(sys.argv) > 3:
            f.write("constexpr uint32_t kMusicRate = 24000;\n\n")
            emit("kMusic", read_wav(sys.argv[3], 24000), f)
        else:
            f.write("constexpr uint32_t kMusicRate = %d;\n\n" % RATE)
            emit("kMusic", to_int16(music()), f)
        emit("kSweep", to_int16(sweep()), f)


if __name__ == "__main__":
    main()
